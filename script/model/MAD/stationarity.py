"""Historical-window selection (paper Section 3.2 + reference implementation).

The paper proposes to automatically select the length K of the stationary
window used to estimate P by a *stationarity test*: hypothesise that the K
most recent slices are generated by a single model P, estimate P on that
window (eq. 9), decompose every slice of the window with the multi-scale
analysis, and compare the *sample variance* of the random variables with the
theoretical variance of Proposition 2.  Only the variance is compared
because P is estimated with the sample mean, which makes the expectations
automatically match (footnote 1 of the paper).  The window minimising

    fitness(K) = || th_var - sample_var ||_2

is retained.

This is a faithful port of the reference code (``MAD.model.fit`` /
``MAD.model.stationarity_test`` in publications1/mad, EUPL-1.2):

* it scans every window length k in [1, span-1] backwards from the most
  recent slice, exactly like the reference loop;
* the sample variance is the population variance over the window, where
  empty slices are treated as the all-zero realization (the reference
  formula ``(sum(x-mean)^2 + (delta - n)*mean^2)/delta``);
* ties keep the *largest* window (reference uses ``fitness <= best_fit``);
* the theoretical variance uses the reference ``get_model_mean_var``.

Three window modes are exposed (task Sec. 9.5):

* ``fixed``     : constant window of K slices ending at t-1.
* ``expanding`` : everything from the first slice up to t-1.
* ``stationary``: the stationarity test above; only this mode is the
  paper-faithful automatic selection (restored from the author's code).
"""

from __future__ import annotations

import numpy as np

from .multiscale import (
    decomposition_coefficients,
    get_model_mean_var,
    next_power_of_two,
    order_relations,
)

__all__ = [
    "WINDOW_MODES",
    "fixed_window_bounds",
    "expanding_window_bounds",
    "window_slice_count",
    "window_active_counts",
    "stationarity_fitness",
    "select_window",
]

WINDOW_MODES = ("fixed", "expanding", "stationary")


def fixed_window_bounds(t: int, first_slice: int, k: int) -> tuple[int, int]:
    """Window of K slices ending at t-1 (past-only, current slice excluded)."""
    hi = t - 1
    lo = max(first_slice, hi - k + 1)
    return lo, hi


def expanding_window_bounds(t: int, first_slice: int) -> tuple[int, int]:
    """All slices from ``first_slice`` up to t-1 (past-only)."""
    return first_slice, t - 1


def window_slice_count(lo: int, hi: int) -> int:
    """Number of slices covered by [lo, hi] (the reference ``delta``)."""
    return hi - lo + 1


def window_active_counts(
    history_slices: dict[int, np.ndarray],
    lo: int,
    hi: int,
    phi_keys_sorted: np.ndarray,
) -> np.ndarray:
    """Active-slice counts of every phi relation inside window [lo, hi].

    ``history_slices``: slice_id -> np.ndarray of active pair keys.
    ``phi_keys_sorted``: sorted array of the candidate pair keys.
    Returns an int array aligned with ``phi_keys_sorted``.
    """
    m = len(phi_keys_sorted)
    counts = np.zeros(m, dtype=np.int64)
    if m == 0:
        return counts
    for s in range(lo, hi + 1):
        active = history_slices.get(s)
        if active is None or len(active) == 0:
            continue
        active = np.asarray(active, dtype=np.int64)
        pos = np.searchsorted(phi_keys_sorted, active)
        valid = pos < m
        pos = pos[valid]
        keys = active[valid]
        match = phi_keys_sorted[pos] == keys
        sel = pos[match]
        if len(sel):
            np.add.at(counts, sel, 1)
    return counts


def _phi_counts_aligned(phi_keys: np.ndarray, counts_sorted: np.ndarray) -> np.ndarray:
    """Reorder counts (aligned to ``np.sort(phi_keys)``) back to the input
    order of ``phi_keys``."""
    order = np.argsort(phi_keys)
    counts = np.empty_like(counts_sorted)
    counts[order] = counts_sorted
    return counts


def stationarity_fitness(
    phi_keys: np.ndarray,
    history_slices: dict[int, np.ndarray],
    lo: int,
    hi: int,
    var_floor: float = 1e-2,
) -> tuple[float, np.ndarray]:
    """Reference ``stationarity_test``: L2 distance between sample and
    theoretical variance of the multi-scale random variables.

    Returns (fitness, counts) where counts are the active-slice counts of
    every phi relation in the window (aligned to ``np.sort(phi_keys)``).
    """
    m = len(phi_keys)
    delta = hi - lo + 1
    if delta <= 0 or m == 0:
        return 0.0, np.zeros(m, dtype=np.int64)

    phi_sorted = np.sort(phi_keys)
    counts = window_active_counts(history_slices, lo, hi, phi_sorted)

    # P estimated on the window (paper eq. 9)
    probs = counts.astype(np.float64) / delta
    order = order_relations(list(range(m)), probs)
    mem_size = next_power_of_two(m)

    # Decompose every non-empty slice of the window
    X: list[np.ndarray] = []
    for s in range(lo, hi + 1):
        active = history_slices.get(s)
        if active is None or len(active) == 0:
            continue
        active = np.asarray(active, dtype=np.int64)
        obs = np.zeros(m, dtype=np.float64)
        pos = np.searchsorted(phi_sorted, active)
        valid = pos < m
        pos = pos[valid]
        keys = active[valid]
        match = phi_sorted[pos] == keys
        idx = pos[match]
        if len(idx):
            obs[idx] = 1.0
        X.append(decomposition_coefficients(obs, order, mem_size))

    th_mean, th_var = get_model_mean_var(probs, order, mem_size)

    if not X:
        # No slice carries any candidate relation -> sample variance is zero
        return float(np.linalg.norm(th_var)), counts

    X_mat = np.vstack(X)
    n_slices = X_mat.shape[0]
    sample_mean = np.sum(X_mat, axis=0) / delta
    sq_mean = (delta - n_slices) * np.power(sample_mean, 2)
    shifted = X_mat - sample_mean
    sample_var = (np.sum(np.power(shifted, 2), axis=0) + sq_mean) / delta

    fitness = float(np.linalg.norm(th_var - sample_var))
    return fitness, counts


def select_window(
    phi_keys: np.ndarray,
    history_slices: dict[int, np.ndarray],
    t: int,
    first_slice: int,
    mode: str = "fixed",
    window_k: int | None = None,
    max_stationary_k: int | None = None,
    var_floor: float = 1e-2,
) -> tuple[int, int, np.ndarray, float, float | None]:
    """Choose the historical window for a query at slice ``t``.

    Returns (lo, hi, counts, delta, fitness) with ``counts`` aligned to the
    input ``phi_keys`` order; ``fitness`` is None unless mode == 'stationary'.
    """
    if mode not in WINDOW_MODES:
        raise ValueError(f"unknown window mode {mode!r}; choose from {WINDOW_MODES}")
    empty = np.zeros(len(phi_keys), dtype=np.int64)
    if t <= first_slice:
        # No usable history yet -> empty window (P = 0 everywhere).
        return t, t - 1, empty, 0, None

    if mode in ("fixed", "expanding"):
        if mode == "fixed":
            if window_k is None or window_k < 1:
                raise ValueError("fixed window mode requires window_k >= 1")
            lo, hi = fixed_window_bounds(t, first_slice, window_k)
        else:
            lo, hi = expanding_window_bounds(t, first_slice)
        delta = window_slice_count(lo, hi)
        phi_sorted = np.sort(phi_keys)
        counts = _phi_counts_aligned(
            phi_keys,
            window_active_counts(history_slices, lo, hi, phi_sorted),
        )
        return lo, hi, counts, delta, None

    # ---- stationary: faithful reference scan over every window length ----
    span = t - first_slice  # max number of history slices
    max_k = max_stationary_k if max_stationary_k else span
    best_fitness: float | None = None
    best_counts_sorted: np.ndarray | None = None
    best_lo = best_hi = t - 1
    best_delta = 0
    for k in range(1, span):
        if k > max_k:
            break
        lo = max(first_slice, t - k)
        hi = t - 1
        fitness, counts_sorted = stationarity_fitness(
            phi_keys, history_slices, lo, hi, var_floor)
        if best_fitness is None or fitness <= best_fitness:
            best_fitness = fitness
            best_counts_sorted = counts_sorted
            best_lo, best_hi = lo, hi
            best_delta = hi - lo + 1
    if best_counts_sorted is None:
        return t, t - 1, empty, 0, best_fitness
    counts = _phi_counts_aligned(phi_keys, best_counts_sorted)
    return best_lo, best_hi, counts, best_delta, best_fitness
