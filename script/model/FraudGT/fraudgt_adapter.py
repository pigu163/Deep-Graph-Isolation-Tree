"""FraudGT adapter — A Simple, Effective, and Efficient Graph Transformer for
Financial Fraud Detection (ACM ICAIF 2024), using the official implementation
(https://github.com/junhongmit/FraudGT).

The official graphgym pipeline is used as-is (model, loader, loss, config):
- data is written in the official AML processed format (``data.pt`` with
  train/val/test HeteroData including ``node``/``to``/``rev_to`` and
  ``split_mask``), built from the canonical event table;
- the AML-Small-HI GINE config drives cfg; wandb is disabled;
- the ``HomoGNNEdgeModel`` (GatedGCN backbone, dim_inner 64, 2 layers) is
  trained with the official weighted cross-entropy and AdamW;
- chronological 60/20/20 splits from splits.json (the official process uses
  a day-balanced 60/20/20 split; boundaries may differ, recorded in config);
- unknown (-1) labels are excluded from the loss but all edges are scored.

Score: P(fraud | edge) from the model (larger = more anomalous).
"""

from __future__ import annotations

import math
import shutil
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import torch

_REPO = Path(__file__).resolve().parents[3]
FG_DIR = _REPO / "source code" / "FraudGT"
if str(FG_DIR) not in sys.path:
    sys.path.insert(0, str(FG_DIR))

import fraudGT  # noqa: E402  (registers custom modules)

# The upstream code calls torch.load without weights_only; torch >= 2.6
# defaults to weights_only=True which rejects PyG HeteroData checkpoints.
# Patch the default so the official loader works (data is generated by us).
_orig_torch_load = torch.load


def _torch_load_compat(*args, **kwargs):
    kwargs.setdefault("weights_only", False)
    return _orig_torch_load(*args, **kwargs)


torch.load = _torch_load_compat
from fraudGT.graphgym.config import cfg, load_cfg  # noqa: E402
from fraudGT.graphgym.loader import create_loader, create_dataset  # noqa: E402
from fraudGT.graphgym.model_builder import create_model  # noqa: E402
from fraudGT.datasets.aml_dataset import z_norm  # noqa: E402
from torch_geometric.data import HeteroData  # noqa: E402
from torch_geometric.utils import index_to_mask  # noqa: E402

TMP_ROOT = _REPO / "tmp" / "fraudgt_data"


def build_hetero_data(events: dict, n: int, edge_index: torch.Tensor,
                      edge_attr: torch.Tensor, y: torch.Tensor,
                      timestamps: torch.Tensor, inds: np.ndarray,
                      e_mask: np.ndarray) -> HeteroData:
    """One HeteroData per split, following the official AMLDataset format."""
    masked_edge_index = edge_index[:, e_mask]
    masked_edge_attr = z_norm(edge_attr[e_mask])
    masked_y = y[e_mask]
    masked_timestamps = timestamps[e_mask]
    data = HeteroData()
    x = torch.ones((int(edge_index.max()) + 1, 1), dtype=torch.float)
    data["node"].x = x
    data["node"].num_nodes = int(x.shape[0])
    data["node", "to", "node"].edge_index = masked_edge_index
    data["node", "to", "node"].edge_attr = masked_edge_attr
    data["node", "to", "node"].y = masked_y
    data["node", "to", "node"].timestamps = masked_timestamps
    data["node", "rev_to", "node"].edge_index = masked_edge_index.flipud()
    data["node", "rev_to", "node"].edge_attr = masked_edge_attr
    data["node", "to", "node"].split_mask = index_to_mask(
        torch.from_numpy(inds), size=masked_edge_index.shape[1])
    return data


def write_data_pt(events: dict, n: int, splits: dict, dataset_name: str) -> Path:
    """Write the official processed data.pt from the canonical event table."""
    src = events["src"][:n].astype(np.int64)
    dst = events["dst"][:n].astype(np.int64)
    label = events["label"][:n].astype(np.int64)
    ts = events["timestamp"][:n].astype(np.float64)
    ts_min = ts.min()

    from script.common.events import event_feature_columns, load_event_features
    from script.common.results import REPO_ROOT as _RR
    import polars as _pl

    feats = {}
    for c in event_feature_columns(events["dataset"]):
        feats[c] = load_event_features(events["dataset"])[c][:n]
    schema = _pl.scan_parquet(_RR / "data" / "processed" / events["dataset"]
                              / "events.parquet").collect_schema().names()
    str_cols = [c for c in ("edge_type", "payment_currency",
                            "receiving_currency") if c in schema]
    if str_cols:
        df = _pl.scan_parquet(_RR / "data" / "processed" / events["dataset"]
                              / "events.parquet").select(str_cols).head(n).collect()
        for c in str_cols:
            feats[c] = df[c].to_numpy()

    cols = [ts - ts_min]
    for c, arr in feats.items():
        if arr.dtype.kind in ("f", "i"):
            v = np.nan_to_num(arr.astype(np.float64), nan=0.0)
        else:
            v = pd.factorize(arr, sort=True)[0].astype(np.float64)
        cols.append(v)
    edge_attr = torch.tensor(np.stack(cols, axis=1), dtype=torch.float)
    edge_index = torch.LongTensor(np.stack([src, dst], axis=0))
    y = torch.LongTensor(label)
    timestamps = torch.Tensor(ts - ts_min)

    tr_s, tr_e = splits["train"]
    va_s, va_e = splits["val"]
    te_s, te_e = splits["test"]
    train_inds = np.arange(tr_s, tr_e)
    val_inds = np.arange(va_s, va_e)
    test_inds = np.arange(te_s, te_e)
    e_train = train_inds
    e_val = np.concatenate([train_inds, val_inds])
    e_test = np.concatenate([train_inds, val_inds, test_inds])

    data_dict = {
        "train": build_hetero_data(events, n, edge_index, edge_attr, y,
                                   timestamps, train_inds, e_train),
        "val": build_hetero_data(events, n, edge_index, edge_attr, y,
                                 timestamps, val_inds, e_val),
        "test": build_hetero_data(events, n, edge_index, edge_attr, y,
                                  timestamps, test_inds, e_test),
    }
    out = TMP_ROOT / "AML" / dataset_name / "processed"
    shutil.rmtree(TMP_ROOT / "AML" / dataset_name, ignore_errors=True)
    out.mkdir(parents=True, exist_ok=True)
    torch.save(data_dict, out / "data.pt")
    torch.save({}, out / "ports.pt")  # processed_file_names requires both
    return TMP_ROOT / "AML"


def run_fraudgt(events: dict, splits: dict, *,
                dataset: str, device: str = "cpu", seed: int = 42,
                n_epochs: int = 3, batch_size: int = 2048,
                neighbor_sizes: list[int] | None = None,
                dim_inner: int = 64, layers_mp: int = 2,
                lr: float = 1e-3, weight_decay: float = 1e-5,
                log=print) -> np.ndarray:
    torch.manual_seed(seed)
    np.random.seed(seed)

    n = len(events["event_id"])
    # FraudGT dataset names are Small-HI / Small-LI; map ours
    ds_map = {"ibm_hi_small": "Small-HI", "ibm_li_small": "Small-LI"}
    fg_name = ds_map.get(dataset, "Small-HI")
    root = write_data_pt(events, n, splits, fg_name)
    neighbor_sizes = neighbor_sizes or [50, 50]

    # ---- graphgym cfg from the official AML-Small-HI config ---------------
    # The yaml files are out of sync with the repo's cfg schema (wandb,
    # add_ports etc. are not defined), so we prune unknown keys.
    import yaml as _yaml
    from fraudGT.graphgym.config import set_cfg

    set_cfg(cfg)

    def _prune(node, d):
        for k in list(d.keys()):
            if k not in node:
                del d[k]
            elif isinstance(d[k], dict):
                child = node[k]
                if hasattr(child, "keys"):
                    _prune(child, d[k])

    yaml_path = FG_DIR / "configs" / "AML-Small-HI" / \
        "AML-Small-HI-GINE+ports.yaml"
    with open(yaml_path) as f:
        cfg_dict = _yaml.safe_load(f)
    _prune(cfg, cfg_dict)
    tmp_yaml = TMP_ROOT / f"cfg_{fg_name}.yaml"
    tmp_yaml.parent.mkdir(parents=True, exist_ok=True)
    with open(tmp_yaml, "w") as f:
        _yaml.safe_dump(cfg_dict, f)
    import argparse
    args = argparse.Namespace(cfg_file=str(tmp_yaml), opts=[],
                              repeat=1, mark_done=False)
    load_cfg(cfg, args)
    cfg.dataset.dir = str(TMP_ROOT)
    cfg.dataset.add_ports = False   # no ports support in this adapter
    cfg.dataset.reverse_mp = False
    cfg.num_threads = 1
    cfg.num_workers = 0
    cfg.device = device
    cfg.train.iter_per_epoch = 16
    cfg.val.iter_per_epoch = 16
    cfg.train.batch_size = batch_size
    cfg.train.neighbor_sizes = neighbor_sizes
    cfg.train.epochs = n_epochs
    cfg.train.ckpt_period = 100
    cfg.gnn.dim_inner = dim_inner
    cfg.gnn.layers_mp = layers_mp
    cfg.optim.lr = lr
    cfg.optim.weight_decay = weight_decay
    cfg.train.add_ego_id = False
    # keep model.type / gnn.layer_type / head from the official yaml

    dataset = create_dataset()
    loaders = create_loader(dataset, shuffle=True)
    tr_loader, val_loader, te_loader = loaders[0], loaders[1], loaders[2]
    model = create_model(to_device=True, dim_in=1, dim_out=2, dataset=dataset)

    loss_fn = torch.nn.functional.binary_cross_entropy_with_logits
    weight = torch.FloatTensor(cfg.model.loss_fun_weight).to(cfg.device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=cfg.optim.lr,
                                  weight_decay=cfg.optim.weight_decay)

    # ---- training (official loop, unknown labels excluded) ----------------
    for epoch in range(n_epochs):
        model.train()
        losses = []
        for batch in tr_loader:
            batch.split = "train"
            batch.to(torch.device(cfg.device))
            pred, true = model(batch)
            pred = pred.squeeze(-1) if pred.ndim > 1 else pred
            true = true.squeeze(-1) if true.ndim > 1 else true
            known = true != -1
            if known.sum().item() == 0:
                continue
            optimizer.zero_grad()
            loss = loss_fn(pred[known], true[known].float(),
                           weight=weight[true[known]])
            loss.backward()
            optimizer.step()
            losses.append(loss.item())
        log(f"  epoch {epoch} loss={np.mean(losses) if losses else 0:.4f}")

    # ---- score all test edges (bypass LoaderWrapper step limit) -----------
    test_data = dataset["test"]
    task = cfg.dataset.task_entity
    mask = test_data[task].split_mask
    edge_label_index = test_data[task].edge_index[:, mask]
    edge_label = test_data[task].y[mask]
    from torch_geometric.loader import LinkNeighborLoader
    te_full = LinkNeighborLoader(
        data=test_data, num_neighbors=neighbor_sizes,
        edge_label_index=(task, edge_label_index), edge_label=edge_label,
        batch_size=batch_size, shuffle=False, num_workers=0)
    model.eval()
    scores = np.full(n, 0.0, dtype=np.float64)
    true_global = torch.where(mask)[0].numpy()  # global event ids of test edges
    preds = []
    with torch.no_grad():
        for batch in te_full:
            batch.split = "test"
            batch.to(torch.device(cfg.device))
            pred, true = model(batch)
            pred = pred.squeeze(-1) if pred.ndim > 1 else pred
            preds.append(torch.sigmoid(pred).detach().cpu().numpy())
    # LinkNeighborLoader (shuffle=False) preserves edge_label_index column
    # order, so concatenated preds align with true_global.
    scores[true_global] = np.concatenate(preds)
    return scores
